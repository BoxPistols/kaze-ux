/**
 * Kaze ロゴ レギュレーション
 *
 * ## シンボルの成り立ち
 *
 * 二本のストロークが左から右へ流れ、右端で上へ抜ける。
 * 「墨で書かれ、風で運ばれる」という世界観を、書の運筆（入り・送り・抜け）
 * と風の上昇気流を重ね合わせて表す。
 *
 * - 主線（下）は長く太く、大きな半径で深く抜ける。副線（上）は短く細く、
 *   小さな半径で控えめに抜ける。この抑揚が運筆の緩急にあたる
 * - 線端を丸めるのは、筆が紙から離れる瞬間の丸みに対応する
 *
 * ### なぜ二本なのか
 *
 * 三本を等幅・等間隔で並べるとハンバーガーメニューの記号に見え、
 * ブランドの識別子として機能しない。要素を二本に絞り、長さ・太さ・
 * 抜けの深さすべてに差をつけることで、記号ではなく筆跡として読ませる。
 *
 * ## なぜ規定するか
 *
 * ロゴは最も小さく、最も多くの場所に置かれる意匠であり、
 * 一度崩れると全体の品位が落ちる。判断の余地を残さないよう、
 * 余白・最小サイズ・配色・禁止事項を数値で固定する。
 */

/** SVG のデザイングリッド（この座標系で全ての比率を定義する） */
export const LOGO_GRID = 32

/**
 * クリアスペース（アイソレーション）
 *
 * シンボルの一辺に対する比率。この内側には文字・罫線・他の図形を
 * 置かない。0.25 は、UI の最小行間（4px / 16px）と一致させた値で、
 * 密なツールバーでも確保できる下限として選んでいる。
 */
export const LOGO_CLEAR_SPACE_RATIO = 0.25

/**
 * 最小サイズ (px)
 *
 * 主線の幅がグリッドの 1/12.3 のため、これ以下では線が 1px を割って
 * 潰れる。用途ごとに下限を分ける。
 */
export const LOGO_MIN_SIZE = {
  /** favicon・アプリアイコンなど、輪郭だけ判別できればよい用途 */
  icon: 16,
  /** UI に置く場合。線の分離が保たれる下限 */
  ui: 24,
  /** ワードマークを併記する場合。文字が読める下限 */
  withWordmark: 20,
} as const

/**
 * 配色バリアント
 *
 * 背景の明度で選ぶ。迷ったら `auto` を使い、コンポーネントに判定させる。
 */
export const LOGO_TONES = [
  /** 正。ブランドティールの塗り面に、実測で決まる文字色 */
  'brand',
  /** 単色（墨）。明るい面に置く。印刷・単色出力もこれ */
  'ink',
  /** 単色（白抜き）。暗い面・写真の上に置く */
  'inverse',
  /** 面を持たず線だけ。ツールバーなど、他の要素と等価に並べる場合 */
  'outline',
] as const

export type LogoTone = (typeof LOGO_TONES)[number]

